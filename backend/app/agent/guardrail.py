    if _SH_DISTRESS.search(n) and _SH_METHOD.search(n):
        return True
    if _SH_COMFORT.search(n) or _SH_ON_PURPOSE.search(n):
        return True
    return bool(_SH_RANK.search(n) and _SH_SELF_USE.search(n))


